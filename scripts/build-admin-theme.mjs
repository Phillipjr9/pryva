import { readFile, writeFile, mkdir, copyFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import postcss from "postcss";
import selectorParser from "postcss-selector-parser";

/**
 * Compile the pinned AdminLTE stylesheet into an isolated console theme.
 *
 * AdminLTE is a Bootstrap template, while Pryva uses Tailwind. Importing its
 * unmodified reset/cards/buttons globally would restyle the storefront too.
 * Every selector is therefore rooted at `.admin-app`; document/theme selectors
 * are mapped to that same boundary. No AdminLTE JavaScript or CDN is shipped:
 * the layout interactions are accessible React components.
 *
 * Run `npm run admin:theme` after upgrading admin-lte or editing the overrides.
 * The checked-in output makes normal builds independent of this generation step.
 */
const root = fileURLToPath(new URL("../", import.meta.url));
const source = path.join(root, "node_modules/admin-lte/dist/css/adminlte.css");
const overrides = path.join(root, "src/styles/admin-console.css");
const destination = path.join(root, "src/styles/adminlte.generated.css");
const parseSelector = selectorParser();
const boundary = "admin-app";

function scopeSelector(selector) {
  return parseSelector.astSync(selector).map((tree) => {
    const first = tree.nodes.find((node) => node.type !== "comment");
    const isDocument = first?.type === "tag" && ["html", "body", ":root"].includes(first.value);
    const isRoot = first?.type === "pseudo" && [":root", ":host"].includes(first.value);
    const isTheme = first?.type === "attribute" && first.attribute === "data-bs-theme";
    if (isDocument || isRoot) {
      first.replaceWith(selectorParser.className({ value: boundary }));
    } else if (isTheme) {
      tree.prepend(selectorParser.className({ value: boundary }));
    } else {
      tree.prepend(selectorParser.combinator({ value: " " }));
      tree.prepend(selectorParser.className({ value: boundary }));
    }
    return String(tree).trim();
  }).join(",\n");
}

const css = await readFile(source, "utf8");
const result = await postcss([
  {
    postcssPlugin: "scope-adminlte",
    Rule(rule) {
      // Keyframe steps are percentages/from/to, not document selectors.
      if (rule.parent?.type === "atrule" && /keyframes$/i.test(rule.parent.name)) return;
      rule.selectors = rule.selectors.map(scopeSelector);
    },
  },
]).process(css, { from: source });
const custom = await readFile(overrides, "utf8");
const packageInfo = JSON.parse(await readFile(path.join(root, "node_modules/admin-lte/package.json"), "utf8"));
const banner = `/* Generated by npm run admin:theme. Do not edit directly.\n * AdminLTE ${packageInfo.version} by ColorlibHQ — MIT (see src/styles/AdminLTE-LICENSE.txt).\n * Selectors isolated to .admin-app; Pryva overrides follow the vendor CSS.\n */\n`;
await mkdir(path.dirname(destination), { recursive: true });
await writeFile(destination, `${banner}${result.css.replace(/^@charset[^;]+;\s*/i, "")}\n\n/* Pryva console overrides */\n${custom}`);
await copyFile(path.join(root, "node_modules/admin-lte/LICENSE"), path.join(root, "src/styles/AdminLTE-LICENSE.txt"));
console.log(`Built src/styles/adminlte.generated.css from AdminLTE ${packageInfo.version}`);
